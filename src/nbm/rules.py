def kql_queries(iocs: list[dict[str, Any]]) -> dict[str, str]:
    domains = sorted({d["domain"] for case in iocs for d in case.get("domains", [])})
    addrs = sorted(
        {a["ip"] for case in iocs for a in case.get("addresses", []) if not is_private_ip(a["ip"])}
    )

    def kql_list(values: list[str]) -> str:
        return ",\n    ".join(f'"{v}"' for v in values) if values else '""'

    queries: dict[str, str] = {}

    queries["nbm-observed-c2-indicators.kql"] = f"""// Generated by network-behavior-mapping. Tier: observed.
// {OBSERVED_NOTE}
// Microsoft Defender XDR / Sentinel advanced hunting.
let c2Domains = dynamic([
    {kql_list(domains)}
]);
let c2Addresses = dynamic([
    {kql_list(addrs)}
]);
let dnsHits =
    DeviceEvents
    | where ActionType == "DnsQueryResponse"
    | extend QueryName = tostring(parse_json(AdditionalFields).DnsQueryString)
    | where QueryName has_any (c2Domains)
    | project Timestamp, DeviceName, Signal = "dns", Indicator = QueryName,
              InitiatingProcessFileName, InitiatingProcessCommandLine;
let connHits =
    DeviceNetworkEvents
    | where RemoteIP in (c2Addresses) or RemoteUrl has_any (c2Domains)
    | project Timestamp, DeviceName, Signal = "connection",
              Indicator = strcat(RemoteIP, ":", RemotePort),
              InitiatingProcessFileName, InitiatingProcessCommandLine;
union dnsHits, connHits
| sort by Timestamp asc
"""

    queries["nbm-behavioral-beaconing.kql"] = """// Generated by network-behavior-mapping. Tier: behavioral.
// Finds destinations contacted on a regular cadence, the way the Python pipeline does:
// interval between successive connections, then the spread of those intervals.
//
// Standard deviation is used here rather than the median absolute deviation the pipeline
// prefers, because KQL has no built-in median-of-deviations; the trade-off is that one long
// gap inflates the spread, so the jitter threshold below is looser than the pipeline's 15%.
//
// Baseline before alerting: software update agents and telemetry clients also beacon.
let lookback = 24h;
let minCheckIns = 6;          // fewer than this and a "pattern" is coincidence
let maxJitterRatio = 0.25;    // stddev / mean interval
let minIntervalSec = 30;      // below this is streaming, not check-in
let maxIntervalSec = 3600;
DeviceNetworkEvents
| where Timestamp > ago(lookback)
| where ActionType == "ConnectionSuccess"
| where not (ipv4_is_private(RemoteIP)) and isnotempty(RemoteIP)
| project Timestamp, DeviceId, DeviceName, RemoteIP, RemotePort, RemoteUrl,
          InitiatingProcessFileName, InitiatingProcessCommandLine
| order by DeviceId, RemoteIP, RemotePort, Timestamp asc
| extend PreviousTimestamp = prev(Timestamp), PreviousKey = prev(strcat(DeviceId, RemoteIP, RemotePort))
| extend CurrentKey = strcat(DeviceId, RemoteIP, RemotePort)
| where PreviousKey == CurrentKey
| extend IntervalSec = datetime_diff('second', Timestamp, PreviousTimestamp)
// Collapse parallel sockets opened for a single check-in.
| where IntervalSec >= 1
| summarize CheckIns = count(),
            MeanInterval = avg(IntervalSec),
            StdDevInterval = stdev(IntervalSec),
            FirstSeen = min(Timestamp),
            LastSeen = max(Timestamp),
            Processes = make_set(InitiatingProcessFileName, 5),
            Urls = make_set(RemoteUrl, 5)
    by DeviceId, DeviceName, RemoteIP, RemotePort
| where CheckIns >= minCheckIns
| where MeanInterval between (minIntervalSec .. maxIntervalSec)
| extend JitterRatio = iff(MeanInterval > 0, StdDevInterval / MeanInterval, 1.0)
| where JitterRatio <= maxJitterRatio
| extend BeaconScore = round(100 * (0.7 * (1 - JitterRatio) + 0.3 * min_of(1.0, CheckIns / 20.0)), 1)
| project DeviceName, RemoteIP, RemotePort, CheckIns,
          IntervalSec = round(MeanInterval, 1), JitterPct = round(JitterRatio * 100, 1),
          BeaconScore, FirstSeen, LastSeen, Processes, Urls
| sort by BeaconScore desc
"""

    queries["nbm-behavioral-nonstandard-port-c2.kql"] = """// Generated by network-behavior-mapping. Tier: behavioral.
// Long-lived outbound sessions to uncommon ports, the shape a persistent RAT socket takes.
// Derived from a Remcos session held open 52 minutes on tcp/3980 and a Raspberry Robin
// infection using tcp/9001, tcp/110 and tcp/28003.
let lookback = 24h;
let commonPorts = dynamic([80, 88, 123, 135, 389, 443, 445, 465, 587, 636, 993, 995, 3128, 3389, 8080, 8443]);
let minSessionSeconds = 120;
DeviceNetworkEvents
| where Timestamp > ago(lookback)
| where ActionType == "ConnectionSuccess" and Protocol == "Tcp"
| where not (ipv4_is_private(RemoteIP))
| where RemotePort !in (commonPorts)
| summarize FirstSeen = min(Timestamp), LastSeen = max(Timestamp), Connections = count(),
            Processes = make_set(InitiatingProcessFileName, 5)
    by DeviceId, DeviceName, RemoteIP, RemotePort
| extend SessionSeconds = datetime_diff('second', LastSeen, FirstSeen)
| where SessionSeconds >= minSessionSeconds
| project DeviceName, RemoteIP, RemotePort, Connections, SessionSeconds,
          FirstSeen, LastSeen, Processes
| sort by SessionSeconds desc
"""

    queries["nbm-behavioral-dynamic-dns.kql"] = """// Generated by network-behavior-mapping. Tier: behavioral.
// Dynamic DNS lookups, correlated with what the resolving process did next. The correlation
// is what makes this usable: the lookup alone is noisy, but a dynamic DNS name resolved by a
// process that then opens a long-lived socket is not.
let lookback = 24h;
let ddnsSuffixes = dynamic([".duckdns.org", ".no-ip.org", ".no-ip.com", ".no-ip.biz",
                            ".ddns.net", ".hopto.org", ".zapto.org", ".sytes.net",
                            ".serveo.net", ".ngrok.io"]);
let lookups =
    DeviceEvents
    | where Timestamp > ago(lookback)
    | where ActionType == "DnsQueryResponse"
    | extend QueryName = tostring(parse_json(AdditionalFields).DnsQueryString)
    | where QueryName has_any (ddnsSuffixes)
    | project LookupTime = Timestamp, DeviceId, DeviceName, QueryName,
              InitiatingProcessId, InitiatingProcessFileName;
lookups
| join kind=leftouter (
    DeviceNetworkEvents
    | where Timestamp > ago(lookback)
    | project ConnTime = Timestamp, DeviceId, InitiatingProcessId, RemoteIP, RemotePort, RemoteUrl
) on DeviceId, InitiatingProcessId
| where ConnTime between (LookupTime .. (LookupTime + 5m))
| project LookupTime, DeviceName, QueryName, InitiatingProcessFileName,
          ConnTime, RemoteIP, RemotePort
| sort by LookupTime asc
"""

    return queries


