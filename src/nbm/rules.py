"""Emit detection content in four languages from the analysed cases.

Rules come in two tiers, kept in separate files because they age very differently:

  observed   - generated from indicators in these captures. Precise, cheap, and perishable;
               the domains and addresses rotate within days.
  behavioral - hand-written from the patterns the captures demonstrate rather than the values
               they contain. These survive infrastructure changes and are the point of the
               exercise, but they need tuning against a real baseline before deployment.

Suricata SIDs are allocated from the 9000000 local range.
"""

from __future__ import annotations

from typing import Any, Iterable

from .util import DETECTIONS_DIR, case_output_dir, is_private_ip, log, read_json, write_json

SID_BASE = 9000000

HEADER = """# Generated by network-behavior-mapping. Do not edit by hand; run `python cli.py rules`.
#
# Tier: {tier}
# {note}
"""

OBSERVED_NOTE = (
    "Indicator-based. Precise but perishable - the infrastructure below rotates quickly."
)
BEHAVIORAL_NOTE = (
    "Pattern-based. Survives infrastructure rotation, but must be baselined in your "
    "environment before it is enabled in blocking or high-severity mode."
)


def _load(cases: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    loaded = []
    for case in cases:
        path = case_output_dir(case["id"]) / "iocs.json"
        if path.exists():
            loaded.append(read_json(path))
        else:
            log.warning("%s: no iocs.json, run 'analyze' first", case["id"])
    return loaded


def _escape(value: str) -> str:
    return value.replace('"', '\\"').replace(";", "\\;")


