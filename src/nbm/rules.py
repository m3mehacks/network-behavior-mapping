def rules_all(cases: Iterable[dict[str, Any]]) -> None:
    iocs = _load(cases)
    if not iocs:
        log.error("no analysed cases; run 'analyze' first")
        return

    suricata_dir = DETECTIONS_DIR / "suricata"
    zeek_dir = DETECTIONS_DIR / "zeek"
    sigma_dir = DETECTIONS_DIR / "sigma"
    kql_dir = DETECTIONS_DIR / "kql"
    for directory in (suricata_dir, zeek_dir, sigma_dir, kql_dir):
        directory.mkdir(parents=True, exist_ok=True)

    observed, behavioral = suricata_rules(iocs)
    (suricata_dir / "nbm-observed.rules").write_text(observed, encoding="utf-8")
    (suricata_dir / "nbm-behavioral.rules").write_text(behavioral, encoding="utf-8")

    zeek_observed, zeek_ja3, zeek_behavioral = zeek_scripts(iocs)
    (zeek_dir / "nbm-observed.zeek").write_text(zeek_observed, encoding="utf-8")
    (zeek_dir / "nbm-observed-ja3.zeek").write_text(zeek_ja3, encoding="utf-8")
    (zeek_dir / "nbm-behavioral.zeek").write_text(zeek_behavioral, encoding="utf-8")

    for name, text in sigma_rules(iocs).items():
        (sigma_dir / name).write_text(text, encoding="utf-8")

    for name, text in kql_queries(iocs).items():
        (kql_dir / name).write_text(text, encoding="utf-8")

    counts = {
        "suricata": observed.count("sid:") + behavioral.count("sid:"),
        "zeek": 3,
        "sigma": len(sigma_rules(iocs)),
        "kql": len(kql_queries(iocs)),
    }
    write_json(DETECTIONS_DIR / "index.json", {"generated_from": [c["case"] for c in iocs], "counts": counts})
    log.info(
        "wrote %d Suricata rules, %d Zeek scripts, %d Sigma rules, %d KQL queries",
        counts["suricata"],
        counts["zeek"],
        counts["sigma"],
        counts["kql"],
    )
