def zeek_scripts(iocs: list[dict[str, Any]]) -> tuple[str, str, str]:
    domains, addrs, ja3s_, ja4s_ = set(), set(), set(), set()
    for case in iocs:
        domains |= {d["domain"] for d in case.get("domains", [])}
        addrs |= {a["ip"] for a in case.get("addresses", []) if not is_private_ip(a["ip"])}
        for fp in case.get("tls_fingerprints", []):
            if fp.get("ja3"):
                ja3s_.add(fp["ja3"])
            if fp.get("ja4"):
                ja4s_.add(fp["ja4"])

    def zeek_set(values, kind: str) -> str:
        if not values:
            return f"set of {kind}"
        rendered = ", ".join(
            f'"{v}"' if kind == "string" else str(v) for v in sorted(values)
        )
        return f"set({rendered})"

    observed = f"""##! Generated by network-behavior-mapping. Tier: observed.
##! {OBSERVED_NOTE}
##!
##! Uses only base Zeek scripts, so it loads with no packages installed.
##! Load with: zeek -r capture.pcap nbm-observed.zeek

@load base/frameworks/notice
@load base/protocols/dns
@load base/protocols/ssl

module NBM;

export {{
    redef enum Notice::Type += {{
        NBM::Observed_C2_Domain,
        NBM::Observed_C2_Address,
    }};

    const c2_domains: set[string] = {zeek_set(domains, "string")} &redef;
    const c2_addresses: set[addr] = {zeek_set(addrs, "addr")} &redef;
}}

function check_name(c: connection, name: string, how: string)
    {{
    if ( to_lower(name) in c2_domains )
        NOTICE([$note=NBM::Observed_C2_Domain,
                $conn=c,
                $msg=fmt("%s references known C2 domain %s", how, name),
                $identifier=to_lower(name),
                $suppress_for=1hr]);
    }}

event dns_request(c: connection, msg: dns_msg, query: string, qtype: count, qclass: count)
    {{
    check_name(c, query, "DNS query");
    }}

## A name can be contacted without a captured lookup, so SNI is checked as well.
event ssl_extension_server_name(c: connection, is_client: bool, names: string_vec)
    {{
    if ( ! is_client )
        return;
    for ( i in names )
        check_name(c, names[i], "TLS SNI");
    }}

event connection_established(c: connection)
    {{
    if ( c$id$resp_h in c2_addresses )
        NOTICE([$note=NBM::Observed_C2_Address,
                $conn=c,
                $msg=fmt("Connection to known C2 address %s:%s", c$id$resp_h, c$id$resp_p),
                $identifier=cat(c$id$resp_h),
                $suppress_for=1hr]);
    }}
"""

    ja3_script = f"""##! Generated by network-behavior-mapping. Tier: observed.
##!
##! REQUIRES the JA3 package, which is not part of base Zeek:
##!     zkg install zeek/salesforce/ja3
##! Kept in its own file so that nbm-observed.zeek loads without it.
##!
##! These fingerprints identify the TLS client library, not the malware. The JA4
##! t12d180700_4b22cbed5bed_2dae41c691ec below is the default Windows schannel client and
##! appears in three unrelated families in this dataset, so scope any alert to a destination
##! rather than firing on the fingerprint alone.

@load base/frameworks/notice
@load base/protocols/ssl

module NBM;

export {{
    redef enum Notice::Type += {{
        NBM::Observed_Client_Fingerprint,
    }};

    const c2_ja3: set[string] = {zeek_set(ja3s_, "string")} &redef;
}}

event ssl_established(c: connection)
    {{
    if ( ! c?$ssl || ! c$ssl?$ja3 )
        return;

    if ( c$ssl$ja3 in c2_ja3 )
        NOTICE([$note=NBM::Observed_Client_Fingerprint,
                $conn=c,
                $msg=fmt("TLS client fingerprint %s seen with malware in this dataset (server %s)",
                         c$ssl$ja3, c$id$resp_h),
                $identifier=cat(c$ssl$ja3, c$id$resp_h),
                $suppress_for=1hr]);
    }}
"""

    behavioral = """##! Generated by network-behavior-mapping. Tier: behavioral.
##! Pattern-based detections derived from the captures rather than their indicator values.
##!
##! Beaconing is scored the same way the Python pipeline scores it: connection start times
##! per destination, median interval, and median absolute deviation as the jitter measure.
##! MAD is used rather than variance so a single long pause does not mask a steady cadence.
##!
##! Load with: zeek -r capture.pcap nbm-behavioral.zeek

@load base/frameworks/notice
@load base/protocols/conn
@load base/protocols/ssl

module NBM;

export {
    redef enum Notice::Type += {
        NBM::Periodic_Beacon,
        NBM::TLS_On_Unexpected_Port,
        NBM::TLS_Port_Without_TLS,
    };

    ## Minimum check-ins before a cadence claim is made.
    const beacon_min_events = 5 &redef;
    ## Maximum jitter, as a fraction of the median interval, still considered regular.
    const beacon_max_jitter = 0.15 &redef;
    ## Cadences outside this range, in seconds, are transfers or noise rather than check-ins.
    const beacon_min_interval = 1.0 &redef;
    const beacon_max_interval = 3600.0 &redef;

    const expected_tls_ports: set[port] = {
        443/tcp, 8443/tcp, 993/tcp, 995/tcp, 465/tcp, 587/tcp, 636/tcp, 989/tcp, 990/tcp
    } &redef;
}

## Connection start times per destination. Timestamps are kept as doubles rather than as
## Zeek intervals so that the median and absolute-value arithmetic below is unambiguous.
global contact_times: table[addr, addr, port] of vector of double &create_expire=6hrs;

## Connections on a TLS port are recorded so that sessions which never negotiate TLS can be
## reported when they end.
global tls_seen: set[string] &create_expire=1hr;

function median(values: vector of double): double
    {
    local n = |values|;
    if ( n == 0 )
        return 0.0;

    local sorted = sort(values, function(a: double, b: double): int
        { return a < b ? -1 : (a == b ? 0 : 1); });

    if ( n % 2 == 1 )
        return sorted[n / 2];
    return (sorted[n / 2 - 1] + sorted[n / 2]) / 2.0;
    }

event connection_established(c: connection)
    {
    local orig = c$id$orig_h;
    local resp = c$id$resp_h;
    local dport = c$id$resp_p;

    if ( Site::is_local_addr(resp) )
        return;

    if ( [orig, resp, dport] !in contact_times )
        contact_times[orig, resp, dport] = vector();

    contact_times[orig, resp, dport] += time_to_double(network_time());

    local times = contact_times[orig, resp, dport];
    if ( |times| < beacon_min_events )
        return;

    local gaps: vector of double;
    for ( i in times )
        {
        if ( i == 0 )
            next;

        local gap = times[i] - times[i - 1];
        # Collapse parallel sockets opened for a single check-in.
        if ( gap >= 1.0 )
            gaps += gap;
        }

    if ( |gaps| < beacon_min_events - 1 )
        return;

    local med = median(gaps);
    if ( med < beacon_min_interval || med > beacon_max_interval )
        return;

    local deviations: vector of double;
    for ( j in gaps )
        deviations += fabs(gaps[j] - med);

    local jitter = median(deviations) / med;
    if ( jitter > beacon_max_jitter )
        return;

    NOTICE([$note=NBM::Periodic_Beacon,
            $conn=c,
            $msg=fmt("%d connections to %s:%s every ~%.0fs (jitter %.1f%%)%s",
                     |times|, resp, dport, med, jitter * 100,
                     med < 10.0 ? " - sub-10s, likely transport keepalive rather than C2" : ""),
            $identifier=cat(orig, resp, dport),
            $suppress_for=1hr]);
    }

event ssl_client_hello(c: connection, version: count, record_version: count, possible_ts: time,
                       client_random: string, session_id: string, ciphers: index_vec,
                       comp_methods: index_vec)
    {
    add tls_seen[c$uid];

    if ( c$id$resp_p !in expected_tls_ports )
        NOTICE([$note=NBM::TLS_On_Unexpected_Port,
                $conn=c,
                $msg=fmt("TLS handshake to %s on port %s, outside the expected TLS ports",
                         c$id$resp_h, c$id$resp_p),
                $identifier=cat(c$id$resp_h, c$id$resp_p),
                $suppress_for=1hr]);
    }

event connection_state_remove(c: connection)
    {
    if ( c$id$resp_p !in expected_tls_ports )
        return;
    if ( c$uid in tls_seen )
        return;
    if ( ! c?$orig || c$orig$size < 1000 )
        return;

    NOTICE([$note=NBM::TLS_Port_Without_TLS,
            $conn=c,
            $msg=fmt("%d bytes sent to %s:%s with no TLS handshake; the port appears chosen to pass egress filtering",
                     c$orig$size, c$id$resp_h, c$id$resp_p),
            $identifier=cat(c$id$resp_h, c$id$resp_p),
            $suppress_for=1hr]);
    }
"""
    return observed, ja3_script, behavioral


